/**
 * محفظة الجنوب — بوابات بيئة التطوير/الإنتاج
 * ------------------------------------------------------------
 * قنوات مصادقة مفتوحة عمداً لوضع Alpha الداخلي يجب إغلاقها في الإنتاج:
 *   • devCode: إعادة رمز OTP في استجابة /api/auth/otp (بدل قناة SMS).
 *   • demo-login: دخول فوري لأي هاتف من بذور Seed (بما فيها الإدارة).
 * القاعدة: معطلة في الإنتاج إلا بتفعيل صريح عبر ALLOW_DEV_AUTH=1
 * (بيئات اختبار داخلية معزولة فقط — لا تُضبط أبداً على خادم عام).
 */
export function isDevAuth(): boolean {
  return process.env.NODE_ENV !== "production" || process.env.ALLOW_DEV_AUTH === "1";
}
