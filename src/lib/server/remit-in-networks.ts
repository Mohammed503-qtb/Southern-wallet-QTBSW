/**
 * محفظة الجنوب — كتالوج شبكات الصرافة للحوالات الواردة (A-03 — 9-c)
 * ----------------------------------------------------------------
 * أسماء شبكات صرافة يمنية افتراضية (تجريبية — D-01: نظام نقدي مغلق).
 * إدارة المحفظة تصدر حوالة واردة باسم إحدى هذه الشبكات، والمستلم
 * يستلمها برصيد عبر رمز مطالبة 6 أرقام (REMIT_IN_CLAIM).
 * ملاحظة التخزين: لا عمود للشبكة في جدول Remittance (المخطط مغلق) —
 * اسم الشبكة يُخزَّن في counterpartyName لمعاملة REMIT_IN_CLAIM
 * (المرجع نفسه) وفي metadataJson الخاصة بها، واسم المرسل الحقيقي كذلك.
 */

/** الشبكات المدعومة في النسخة التجريبية (Beta) */
export const REMIT_IN_NETWORKS: readonly string[] = [
  "الفلوس للصرافة",
  "الخليج للصرافة",
  "برقة للصرافة",
  "الهناء للصرافة",
  "اليمن الأولى للصرافة",
];

/** التحقق أن اسم الشبكة من الكتالوج (تطابق نصي بعد التقليم) */
export function isValidRemitInNetwork(name: string): boolean {
  const clean = name.trim();
  return REMIT_IN_NETWORKS.some((n) => n === clean);
}

/** رسالة الخطأ الموحدة لشبكة غير مدعومة */
export const REMIT_IN_NETWORK_ERROR = "شبكة صرافة غير مدعومة — اختر من قائمة الشبكات المتاحة";
